// A synthetic run with more noise than the terminal shows: the report
// caps the table at 20 items like the terminal does, so the file stays
// paste-sized, and says how many more there are.
function syntheticRun(noiseCount) {
  const noise = Array.from({ length: noiseCount }, (_, i) => ({
    label: `logs/app-${i}.log`, reason: 'log file', bytes: 1000, tokens: 250,
  }));
  return {
    root: '/repo',
    overall: false,
    checks: {
      context: {
        result: {
          root: '/repo', files: noiseCount, bytes: noiseCount * 1000,
          score: 40, status: 'Noisy', truncated: false,
          breakdown: [{ label: 'logs', bytes: noiseCount * 1000, share: 100, lost: 15, weight: 15 }],
          noise, review: [], reviewSuggestions: [],
          suggestions: ['logs/*.log'], estimatedTokens: noiseCount * 250,
        },
        passed: false,
        verdict: 'noisy (score 40/100)',
      },
    },
    skipped: [],
    summary: {
      checks: { total: 1, passed: 0, failed: 1, skipped: 0 },
      contextNoiseBytes: noiseCount * 1000, cacheSavedPct: null,
    },
  };
}

test('report: noise table caps at 20 items and counts the rest', () => {
  const md = formatReportMarkdown(syntheticRun(25));
  assert.match(md, /\| logs\/app-19\.log \|/);
  assert.doesNotMatch(md, /\| logs\/app-20\.log \|/);
  assert.match(md, /… and 5 more/);
  assert.match(md, /Top 3 noise items: ≈ 750 tokens \(12% of this noise\)/);
});

test('report: a short noise list has no cap line', () => {
  const md = formatReportMarkdown(syntheticRun(2));
  assert.doesNotMatch(md, /… and \d+ more/);
  assert.match(md, /Top 2 noise items: ≈ 500 tokens \(100% of this noise\)/);
});

test('report: the directory rollup renders when the noise spans directories', () => {
  const run = syntheticRun(2);
  run.checks.context.result.topDirectories = [
    { directory: 'logs/', bytes: 1600, tokens: 400, share: 80 },
    { directory: '(root)', bytes: 400, tokens: 100, share: 20 },
  ];
  const md = formatReportMarkdown(run);
  assert.match(md, /^Top directories by noise:$/m);
  assert.match(md, /^- logs\/ — ≈ 400 tokens \(80% of this noise\)$/m);
  assert.match(md, /^- \(root\) — ≈ 100 tokens \(20% of this noise\)$/m);
});

test('report: no directory rollup when the noise is one directory', () => {
  // The demo repo lists a single noise item (data/export.json), so
  // the rollup is empty and the report must not print its header.
  const run = runAll({ root: demoRepo, flakesDir: demoRuns });
  const md = formatReportMarkdown(run);
  assert.doesNotMatch(md, /Top directories by noise/);
});

test('report: the binaries section lists the hardening table', () => {
  const run = runAll({ root: demoRepo });
  run.checks.binaries = {
    result: {
      root: demoRepo, top: 5, files: 10, checkedFiles: 2, totalBinaries: 1,
      binaries: [{
        file: 'bin/tool', bytes: 20480, format: 'elf', arch: 'x86-64', entropy: 5.21,
        hardening: {
          pie: 'disabled', nx: 'enabled', relro: 'disabled', stackProtector: 'unknown',
          fortify: 'unknown', cet: 'disabled', btiPac: 'not_applicable',
          rpath: 'disabled', runpath: 'disabled', stripped: 'enabled',
        },
        notes: ['stack protector: no dynamic symbol table — cannot tell from headers'],
      }],
    },
    passed: true,
    verdict: '1 native binary checked — see the hardening table',
  };
  const md = formatReportMarkdown(run);
  assert.match(md, /^## binaries$/m);
  assert.match(md, /^- bin\/tool — 20\.0 KB, elf x86-64, entropy 5\.21$/m);
  assert.match(md, /pie: disabled  nx: enabled  relro: disabled  stripped: enabled/);
  assert.match(md, /stack protector: unknown  fortify: unknown  cet: disabled  bti\/pac: not_applicable  rpath: disabled  runpath: disabled/);
  assert.match(md, /note: stack protector: no dynamic symbol table/);
  assert.match(md, /A checkup, not a security audit/);
  assert.match(md, /^Verdict: PASS — 1 native binary checked/m);
});

